// ⚠️ 收字标准是「码位只属于简体」：例如 說/説/说 三个是不同码位，收 说 没问题；
// 而 内 条 件 点 准 任 督 核 算 屏 随 这些字简体和日文新字体共用同一个码位
// （サーバー内部エラー、条件、点を教えて…全会误伤），一个都不能收。
export const SIMPLIFIED_ONLY = new Set(
  ('达讯认荐语议试说请详该记论评计设访课谢调载车东马鸟龙华汉广门问间关应无为这们时图报复处单边线长页项优击联网从众让还进远连运过导传缓质继续'
   + '题类须务实现见级别态样种业约结经营济费币价买卖购销货运输储备检验签积组织构标则规范值观识术权责监审账户资产负债')
    .split(''),
);

export function hasSimplified(s) {
  for (const ch of s) if (SIMPLIFIED_ONLY.has(ch)) return true;
  return false;
}
